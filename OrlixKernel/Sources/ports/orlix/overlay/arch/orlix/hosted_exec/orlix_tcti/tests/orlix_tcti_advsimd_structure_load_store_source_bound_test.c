/*
 * Every execution claim below enters through the same EL0 resume path as an
 * ordinary hosted guest.  The terminating SVC makes the structured result
 * distinguish successful execution from a decoder-only observation.
 */
static unsigned long orlix_tcti_advsimd_structure_map_instruction(struct kunit *test,
							      u32 instruction)
{
	const u32 program[] = { instruction, ORLIX_TCTI_ADVSIMD_STRUCTURE_SVC };
	unsigned long mapped;
	int ret;

	mapped = ksys_mmap_pgoff(0, PAGE_SIZE, PROT_READ | PROT_WRITE,
				 MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
	KUNIT_ASSERT_FALSE(test, IS_ERR_VALUE(mapped));
	ret = orlix_tcti_write_user_data(current->mm, mapped, program, sizeof(program));
	KUNIT_ASSERT_EQ(test, 0, ret);
	ret = sys_mprotect(mapped, PAGE_SIZE, PROT_READ | PROT_EXEC);
	KUNIT_ASSERT_EQ(test, 0, ret);
	return mapped;
}

static struct orlix_tcti_result orlix_tcti_advsimd_structure_resume(
	struct kunit *test, u32 instruction, struct pt_regs *regs,
	unsigned long *mapped)
{
	struct orlix_tcti_result result;

	*mapped = orlix_tcti_advsimd_structure_map_instruction(test, instruction);
	regs->pc = *mapped;
	regs->pstate |= PSR_MODE_EL0t;
	regs->syscallno = NO_SYSCALL;
	result = orlix_tcti_resume_user(current, regs, current->mm);
	KUNIT_EXPECT_EQ(test, ORLIX_TCTI_EXIT_SYSCALL, result.reason);
	KUNIT_EXPECT_EQ(test, 0L, result.status);
	KUNIT_EXPECT_EQ(test, ORLIX_TCTI_ADVSIMD_STRUCTURE_SVC, result.instruction);
	KUNIT_EXPECT_EQ(test, *mapped + 2 * sizeof(u32), result.pc);
	KUNIT_EXPECT_EQ(test, *mapped + 2 * sizeof(u32), regs->pc);
	return result;
}

static void orlix_tcti_advsimd_structure_initialize_state(struct pt_regs *regs,
						     u32 instruction)
{
	unsigned int index;

	for (index = 0; index < ARRAY_SIZE(regs->regs); index++)
		regs->regs[index] = 0x8192a3b4c5d6e700ULL ^
			((u64)instruction << 9) ^ index;
	regs->pc = 0x123456789000ULL;
	regs->sp = 0x23456789a000ULL;
	regs->pstate = PSR_MODE_EL0t | PSR_N_BIT | PSR_C_BIT;
	regs->orig_x0 = 0xd1b54a32d192ed03ULL;
	regs->syscallno = NO_SYSCALL;
	regs->unused = 0x6d5a56c3U;
	for (index = 0; index < ARRAY_SIZE(current->thread.user_simd); index++)
		current->thread.user_simd[index] = 0xfedcba9876543210ULL ^
			((u64)instruction << 13) ^
			(0x0101010101010101ULL * index);
	current->thread.user_simd_valid = 0;
	current->thread.user_fpcr = BIT(22) | BIT(24);
	current->thread.user_fpsr = BIT(4);
}

static u64 orlix_tcti_advsimd_structure_lane_mask(u8 size)
{
	return size == sizeof(u64) ? U64_MAX : GENMASK_ULL(size * 8 - 1, 0);
}

static u64 orlix_tcti_advsimd_structure_read_lane(const u64 *simd, u8 register_index,
						     u8 size, u8 lane)
{
	u8 byte = lane * size;

	return (simd[register_index * 2 + byte / sizeof(u64)] >>
		((byte % sizeof(u64)) * 8)) & orlix_tcti_advsimd_structure_lane_mask(size);
}

static void orlix_tcti_advsimd_structure_write_lane(u64 *simd, u8 register_index,
						      u8 size, u8 lane, u64 value)
{
	u8 byte = lane * size;
	u8 word = register_index * 2 + byte / sizeof(u64);
	u8 shift = (byte % sizeof(u64)) * 8;
	u64 mask = orlix_tcti_advsimd_structure_lane_mask(size) << shift;

	simd[word] = (simd[word] & ~mask) |
		((value & orlix_tcti_advsimd_structure_lane_mask(size)) << shift);
}

static u64 orlix_tcti_advsimd_structure_source_value(u32 ordinal, u8 offset,
							 u8 size)
{
	u64 value = 0;
	u8 byte;

	for (byte = 0; byte < size; byte++)
		value |= (u64)(u8)(ordinal + offset + byte) << (byte * 8);
	return value;
}

static u8 orlix_tcti_advsimd_structure_lane(u32 instruction, u8 access_size)
{
	u8 q = FIELD_GET(BIT(30), instruction);
	u8 s = FIELD_GET(BIT(12), instruction);

	switch (access_size) {
	case 1:
		return (q << 3) | (s << 2) |
			FIELD_GET(GENMASK(11, 10), instruction);
	case 2:
		return (q << 2) | (s << 1) | FIELD_GET(BIT(11), instruction);
	case 4:
		return (q << 1) | s;
	case 8:
		return q;
	default:
		return 0;
	}
}

static void orlix_tcti_advsimd_structure_expected_transfer(
	const struct orlix_tcti_advsimd_structure_contract *contract, u32 instruction,
	const u64 *before_simd, u64 *expected_simd, u8 *memory)
{
	u8 register_index = instruction & GENMASK(4, 0);
	u8 width = instruction & BIT(30) ? contract->q1_semantic_width :
		contract->q0_semantic_width;
	u8 lane = 0;
	u8 element;
	u8 structure;

	if (contract->lane_shape == ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE) {
		lane = orlix_tcti_advsimd_structure_lane(instruction,
			contract->access_size);
		for (structure = 0; structure < contract->structure_count; structure++) {
			u64 value = contract->load ?
				orlix_tcti_advsimd_structure_source_value(contract->ordinal,
					structure * contract->access_size,
					contract->access_size) :
				orlix_tcti_advsimd_structure_read_lane(before_simd,
					(register_index + structure) & 31,
					contract->access_size, lane);

			if (contract->load)
				orlix_tcti_advsimd_structure_write_lane(expected_simd,
					(register_index + structure) & 31, contract->access_size,
					lane, value);
			else
				memcpy(memory + structure * contract->access_size, &value,
					contract->access_size);
		}
		return;
	}

	if (contract->lane_shape == ORLIX_TCTI_ADVSIMD_STRUCTURE_REPLICATE) {
		for (structure = 0; structure < contract->structure_count; structure++)
			for (element = 0; element < width / contract->access_size;
			     element++)
				orlix_tcti_advsimd_structure_write_lane(expected_simd,
					(register_index + structure) & 31, contract->access_size,
					element,
					orlix_tcti_advsimd_structure_source_value(contract->ordinal,
						structure * contract->access_size,
						contract->access_size));
	} else {
		for (element = 0; element < width / contract->access_size; element++)
			for (structure = 0; structure < contract->structure_count;
			     structure++) {
				u8 offset = contract->interleaved ?
					(element * contract->structure_count + structure) *
					contract->access_size :
					(structure * (width / contract->access_size) + element) *
					contract->access_size;
				u64 value = contract->load ?
					orlix_tcti_advsimd_structure_source_value(contract->ordinal, offset,
						contract->access_size) :
					orlix_tcti_advsimd_structure_read_lane(before_simd,
						(register_index + structure) & 31,
						contract->access_size, element);

				if (contract->load)
					orlix_tcti_advsimd_structure_write_lane(expected_simd,
						(register_index + structure) & 31,
						contract->access_size, element, value);
				else
					memcpy(memory + offset, &value, contract->access_size);
			}
	}

	if (contract->load && !(instruction & BIT(30)) &&
	    contract->lane_shape != ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE)
		for (structure = 0; structure < contract->structure_count; structure++)
			expected_simd[((register_index + structure) & 31) * 2 + 1] = 0;
}

static void orlix_tcti_advsimd_structure_every_contract_row_executes(
	struct kunit *test)
{
	size_t index;

	KUNIT_ASSERT_NOT_NULL(test, current->mm);
	for (index = 0; index < ARRAY_SIZE(orlix_tcti_advsimd_structure_contracts);
	     index++) {
		const struct orlix_tcti_advsimd_structure_contract *contract =
			&orlix_tcti_advsimd_structure_contracts[index];
		unsigned int q;

		for (q = 0; q < 2; q++) {
			struct pt_regs regs = {};
			struct pt_regs expected_regs;
			u64 before_simd[ARRAY_SIZE(current->thread.user_simd)];
			u64 expected_simd[ARRAY_SIZE(current->thread.user_simd)];
			u8 memory[80];
			u8 observed[80];
			u32 instruction = contract->pattern | (q ? BIT(30) : 0) |
				(8U << 5) | 30U;
			unsigned long address;
			unsigned long mapped;
			u8 width = q ? contract->q1_semantic_width :
				contract->q0_semantic_width;
			u8 transfer_size = contract->lane_shape ==
				ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE || contract->lane_shape ==
				ORLIX_TCTI_ADVSIMD_STRUCTURE_REPLICATE ? contract->access_size :
				width;
			u8 total = contract->structure_count * transfer_size;
			u8 writeback_register = (instruction >> 16) & 31;
			u64 writeback = total + 7;
			int ret;

			KUNIT_ASSERT_LE_MSG(test, total, sizeof(memory) - 16,
				"ordinal=%u leaf=%s", contract->ordinal, contract->leaf_id);
			address = ksys_mmap_pgoff(0, PAGE_SIZE, PROT_READ | PROT_WRITE,
				MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
			KUNIT_ASSERT_FALSE(test, IS_ERR_VALUE(address));
			orlix_tcti_advsimd_structure_initialize_state(&regs, instruction);
			regs.regs[8] = address + 8;
			if (contract->index_mode == ORLIX_TCTI_MEMORY_INDEX_POST &&
			    writeback_register != 31) {
				KUNIT_ASSERT_NE_MSG(test, 8U, writeback_register,
					"ordinal=%u leaf=%s", contract->ordinal,
					contract->leaf_id);
				regs.regs[writeback_register] = writeback;
			}
			memcpy(before_simd, current->thread.user_simd, sizeof(before_simd));
			memcpy(expected_simd, before_simd, sizeof(expected_simd));
			memset(memory, 0xa5, sizeof(memory));
			for (ret = 0; ret < total; ret++)
				memory[8 + ret] = contract->ordinal + ret;
			KUNIT_ASSERT_EQ(test, 0, orlix_tcti_write_user_data(current->mm, address,
				memory, sizeof(memory)));
			orlix_tcti_advsimd_structure_expected_transfer(contract, instruction,
				before_simd, expected_simd, memory + 8);
			expected_regs = regs;
			if (contract->index_mode == ORLIX_TCTI_MEMORY_INDEX_POST)
				expected_regs.regs[8] += writeback_register == 31 ?
					total : writeback;
			orlix_tcti_advsimd_structure_resume(test, instruction, &regs, &mapped);
			expected_regs.pc = mapped + 2 * sizeof(u32);
			KUNIT_EXPECT_MEMEQ_MSG(test, &expected_regs, &regs, sizeof(regs),
				"ordinal=%u leaf=%s q=%u", contract->ordinal,
				contract->leaf_id, q);
			KUNIT_EXPECT_MEMEQ_MSG(test, expected_simd, current->thread.user_simd,
				sizeof(expected_simd), "ordinal=%u leaf=%s q=%u",
				contract->ordinal, contract->leaf_id, q);
			KUNIT_EXPECT_EQ_MSG(test, 1UL, current->thread.user_simd_valid,
				"ordinal=%u leaf=%s q=%u", contract->ordinal,
				contract->leaf_id, q);
			KUNIT_EXPECT_EQ_MSG(test, BIT(22) | BIT(24), current->thread.user_fpcr,
				"ordinal=%u leaf=%s q=%u", contract->ordinal,
				contract->leaf_id, q);
			KUNIT_EXPECT_EQ_MSG(test, BIT(4), current->thread.user_fpsr,
				"ordinal=%u leaf=%s q=%u", contract->ordinal,
				contract->leaf_id, q);
			KUNIT_ASSERT_EQ(test, 0, orlix_tcti_read_user_data(current->mm, address,
				observed, sizeof(observed)));
			if (contract->load) {
				KUNIT_EXPECT_MEMEQ_MSG(test, memory, observed, sizeof(memory),
					"ordinal=%u leaf=%s q=%u", contract->ordinal,
					contract->leaf_id, q);
			} else {
				KUNIT_EXPECT_MEMEQ_MSG(test, memory, observed, sizeof(memory),
					"ordinal=%u leaf=%s q=%u", contract->ordinal,
					contract->leaf_id, q);
			}
			KUNIT_EXPECT_EQ(test, 0, vm_munmap(mapped, PAGE_SIZE));
			KUNIT_EXPECT_EQ(test, 0, vm_munmap(address, PAGE_SIZE));
		}
	}
}

static void orlix_tcti_advsimd_structure_every_source_leaf_reaches_decoder(
	struct kunit *test)
{
	const struct orlix_tcti_target_instruction_artifact *artifact =
		orlix_tcti_target_instruction_artifact_canonical();
	size_t index;
	u32 observed = 0;

	KUNIT_ASSERT_NOT_NULL(test, artifact);
	KUNIT_ASSERT_GT(test, artifact->leaf_count,
			ORLIX_TCTI_ADVSIMD_STRUCTURE_LAST_SOURCE);
	KUNIT_ASSERT_EQ(test, ORLIX_TCTI_ADVSIMD_STRUCTURE_SOURCE_COUNT,
			ARRAY_SIZE(orlix_tcti_advsimd_structure_contracts));

	for (index = 0; index < ARRAY_SIZE(orlix_tcti_advsimd_structure_contracts);
	     index++) {
		const struct orlix_tcti_advsimd_structure_contract *expected =
			&orlix_tcti_advsimd_structure_contracts[index];
		const struct orlix_tcti_target_instruction_artifact_leaf *leaf =
			&artifact->leaves[expected->ordinal];
		const char *leaf_id = orlix_tcti_advsimd_structure_artifact_string(
			artifact, leaf->name_offset);
		const char *mnemonic = orlix_tcti_advsimd_structure_artifact_string(
			artifact, leaf->mnemonic_offset);
		const char *operation_id = orlix_tcti_advsimd_structure_artifact_string(
			artifact, leaf->operation_offset);
		struct orlix_tcti_decoded_instruction q0;
		struct orlix_tcti_decoded_instruction q1;

		KUNIT_EXPECT_EQ_MSG(test, ORLIX_TCTI_ADVSIMD_STRUCTURE_FIRST_SOURCE + index,
			expected->ordinal, "contract index=%zu", index);
		KUNIT_ASSERT_NOT_NULL_MSG(test, leaf_id, "ordinal=%u",
			expected->ordinal);
		KUNIT_ASSERT_NOT_NULL_MSG(test, mnemonic, "ordinal=%u",
			expected->ordinal);
		KUNIT_ASSERT_NOT_NULL_MSG(test, operation_id, "ordinal=%u",
			expected->ordinal);
		KUNIT_EXPECT_STREQ_MSG(test, expected->leaf_id, leaf_id,
			"ordinal=%u", expected->ordinal);
		KUNIT_EXPECT_STREQ_MSG(test, expected->mnemonic, mnemonic,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_STREQ_MSG(test, expected->operation_id, operation_id,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->mask, leaf->encoding_mask,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->pattern, leaf->encoding_pattern,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);

		q0 = orlix_tcti_decode_aarch64(expected->pattern);
		q1 = orlix_tcti_decode_aarch64(expected->pattern | BIT(30));
		KUNIT_EXPECT_EQ_MSG(test, expected->decode_class, q0.decode_class,
			"ordinal=%u leaf=%s q=0", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->decode_class, q1.decode_class,
			"ordinal=%u leaf=%s q=1", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->pattern, q0.instruction,
			"ordinal=%u leaf=%s q=0", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->pattern | BIT(30), q1.instruction,
			"ordinal=%u leaf=%s q=1", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->load, q0.load,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->structure_count,
			q0.simd_structure_count, "ordinal=%u leaf=%s",
			expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->access_size, q0.access_size,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		if (expected->lane_shape == ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE) {
			/* The current decoder exposes lane shape, not vector width. */
			KUNIT_EXPECT_EQ_MSG(test, 0U, q0.result_size,
				"ordinal=%u leaf=%s q=0", expected->ordinal,
				expected->leaf_id);
			KUNIT_EXPECT_EQ_MSG(test, 0U, q1.result_size,
				"ordinal=%u leaf=%s q=1", expected->ordinal,
				expected->leaf_id);
		} else {
			KUNIT_EXPECT_EQ_MSG(test, expected->q0_semantic_width,
				q0.result_size, "ordinal=%u leaf=%s q=0",
				expected->ordinal, expected->leaf_id);
			KUNIT_EXPECT_EQ_MSG(test, expected->q1_semantic_width,
				q1.result_size, "ordinal=%u leaf=%s q=1",
				expected->ordinal, expected->leaf_id);
		}
		KUNIT_EXPECT_EQ_MSG(test, expected->index_mode, q0.memory_index_mode,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->interleaved, q0.simd_interleaved,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test,
			expected->lane_shape == ORLIX_TCTI_ADVSIMD_STRUCTURE_REPLICATE,
			q0.simd_replicate, "ordinal=%u leaf=%s", expected->ordinal,
			expected->leaf_id);
		if (expected->lane_shape == ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE)
			KUNIT_EXPECT_FALSE_MSG(test, q0.simd_replicate,
				"ordinal=%u leaf=%s lane form", expected->ordinal,
				expected->leaf_id);
		observed++;
	}

	KUNIT_EXPECT_EQ(test, ORLIX_TCTI_ADVSIMD_STRUCTURE_SOURCE_COUNT, observed);
}


static void orlix_tcti_advsimd_structure_single_lane_writeback_and_pc(
	struct kunit *test)
{
	const u8 source[] = { 0x5a, 0x6b, 0x7c, 0x8d };
	struct pt_regs regs = {};
	struct orlix_tcti_decoded_instruction decoded;
	unsigned long address;
	unsigned long mapped;
	int ret;

	KUNIT_ASSERT_NOT_NULL(test, current->mm);
	address = ksys_mmap_pgoff(0, PAGE_SIZE, PROT_READ | PROT_WRITE,
				 MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
	KUNIT_ASSERT_FALSE(test, IS_ERR_VALUE(address));
	KUNIT_ASSERT_EQ(test, 0,
		orlix_tcti_write_user_data(current->mm, address, source, sizeof(source)));

	/* LD4 {v31.b-v2.b}[8], [x8], #4. */
	decoded = orlix_tcti_decode_aarch64(0x4d60211fU);
	KUNIT_ASSERT_EQ(test, ORLIX_TCTI_DECODE_SIMD_LOAD_STORE_SINGLE_STRUCTURE,
			decoded.decode_class);
	KUNIT_EXPECT_EQ(test, 4, decoded.simd_structure_count);
	KUNIT_EXPECT_EQ(test, ORLIX_TCTI_MEMORY_INDEX_POST,
			decoded.memory_index_mode);
	current->thread.user_simd[31 * 2 + 1] = 0;
	current->thread.user_simd[0] = 0;
	current->thread.user_simd[1] = 0;
	current->thread.user_simd[2] = 0;
	regs.regs[8] = address;

	orlix_tcti_advsimd_structure_resume(test, 0x4d60211fU, &regs, &mapped);
	KUNIT_EXPECT_EQ(test, address + sizeof(source), regs.regs[8]);
	KUNIT_EXPECT_EQ(test, (u64)source[0],
			current->thread.user_simd[31 * 2 + 1] & 0xffULL);
	KUNIT_EXPECT_EQ(test, (u64)source[1],
			current->thread.user_simd[0] & 0xffULL);
	KUNIT_EXPECT_EQ(test, (u64)source[2],
			current->thread.user_simd[1] & 0xffULL);
	KUNIT_EXPECT_EQ(test, (u64)source[3],
			current->thread.user_simd[2] & 0xffULL);

	KUNIT_EXPECT_EQ(test, 0, vm_munmap(mapped, PAGE_SIZE));
	KUNIT_EXPECT_EQ(test, 0, vm_munmap(address, PAGE_SIZE));
}

