static void orlix_tcti_advsimd_structure_every_source_leaf_reaches_decoder(
	struct kunit *test)
{
	const struct orlix_tcti_target_instruction_artifact *artifact =
		orlix_tcti_target_instruction_artifact_canonical();
	size_t index;
	u32 observed = 0;

	KUNIT_ASSERT_NOT_NULL(test, artifact);
	KUNIT_ASSERT_GT(test, artifact->leaf_count,
			ORLIX_TCTI_ADVSIMD_STRUCTURE_LAST_SOURCE);
	KUNIT_ASSERT_EQ(test, ORLIX_TCTI_ADVSIMD_STRUCTURE_SOURCE_COUNT,
			ARRAY_SIZE(orlix_tcti_advsimd_structure_contracts));

	for (index = 0; index < ARRAY_SIZE(orlix_tcti_advsimd_structure_contracts);
	     index++) {
		const struct orlix_tcti_advsimd_structure_contract *expected =
			&orlix_tcti_advsimd_structure_contracts[index];
		const struct orlix_tcti_target_instruction_artifact_leaf *leaf =
			&artifact->leaves[expected->ordinal];
		const char *leaf_id = orlix_tcti_advsimd_structure_artifact_string(
			artifact, leaf->name_offset);
		const char *mnemonic = orlix_tcti_advsimd_structure_artifact_string(
			artifact, leaf->mnemonic_offset);
		const char *operation_id = orlix_tcti_advsimd_structure_artifact_string(
			artifact, leaf->operation_offset);
		struct orlix_tcti_decoded_instruction q0;
		struct orlix_tcti_decoded_instruction q1;

		KUNIT_EXPECT_EQ_MSG(test, ORLIX_TCTI_ADVSIMD_STRUCTURE_FIRST_SOURCE + index,
			expected->ordinal, "contract index=%zu", index);
		KUNIT_ASSERT_NOT_NULL_MSG(test, leaf_id, "ordinal=%u",
			expected->ordinal);
		KUNIT_ASSERT_NOT_NULL_MSG(test, mnemonic, "ordinal=%u",
			expected->ordinal);
		KUNIT_ASSERT_NOT_NULL_MSG(test, operation_id, "ordinal=%u",
			expected->ordinal);
		KUNIT_EXPECT_STREQ_MSG(test, expected->leaf_id, leaf_id,
			"ordinal=%u", expected->ordinal);
		KUNIT_EXPECT_STREQ_MSG(test, expected->mnemonic, mnemonic,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_STREQ_MSG(test, expected->operation_id, operation_id,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->mask, leaf->encoding_mask,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->pattern, leaf->encoding_pattern,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);

		q0 = orlix_tcti_decode_aarch64(expected->pattern);
		q1 = orlix_tcti_decode_aarch64(expected->pattern | BIT(30));
		KUNIT_EXPECT_EQ_MSG(test, expected->decode_class, q0.decode_class,
			"ordinal=%u leaf=%s q=0", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->decode_class, q1.decode_class,
			"ordinal=%u leaf=%s q=1", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->pattern, q0.instruction,
			"ordinal=%u leaf=%s q=0", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->pattern | BIT(30), q1.instruction,
			"ordinal=%u leaf=%s q=1", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->load, q0.load,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->structure_count,
			q0.simd_structure_count, "ordinal=%u leaf=%s",
			expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->access_size, q0.access_size,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		if (expected->lane_shape == ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE) {
			/* The current decoder exposes lane shape, not vector width. */
			KUNIT_EXPECT_EQ_MSG(test, 0U, q0.result_size,
				"ordinal=%u leaf=%s q=0", expected->ordinal,
				expected->leaf_id);
			KUNIT_EXPECT_EQ_MSG(test, 0U, q1.result_size,
				"ordinal=%u leaf=%s q=1", expected->ordinal,
				expected->leaf_id);
		} else {
			KUNIT_EXPECT_EQ_MSG(test, expected->q0_semantic_width,
				q0.result_size, "ordinal=%u leaf=%s q=0",
				expected->ordinal, expected->leaf_id);
			KUNIT_EXPECT_EQ_MSG(test, expected->q1_semantic_width,
				q1.result_size, "ordinal=%u leaf=%s q=1",
				expected->ordinal, expected->leaf_id);
		}
		KUNIT_EXPECT_EQ_MSG(test, expected->index_mode, q0.memory_index_mode,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->interleaved, q0.simd_interleaved,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test,
			expected->lane_shape == ORLIX_TCTI_ADVSIMD_STRUCTURE_REPLICATE,
			q0.simd_replicate, "ordinal=%u leaf=%s", expected->ordinal,
			expected->leaf_id);
		if (expected->lane_shape == ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE)
			KUNIT_EXPECT_FALSE_MSG(test, q0.simd_replicate,
				"ordinal=%u leaf=%s lane form", expected->ordinal,
					expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->ordinal == 2422U, q0.acquire,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		KUNIT_EXPECT_EQ_MSG(test, expected->ordinal == 2403U, q0.release,
			"ordinal=%u leaf=%s", expected->ordinal, expected->leaf_id);
		observed++;
	}

	KUNIT_EXPECT_EQ(test, ORLIX_TCTI_ADVSIMD_STRUCTURE_SOURCE_COUNT, observed);
}

static void orlix_tcti_advsimd_structure_authoritative_encoding_space(
	struct kunit *test)
{
	const struct orlix_tcti_target_instruction_artifact *artifact =
		orlix_tcti_target_instruction_artifact_canonical();
	static const u8 boundaries[] = { 0U, 1U, 30U, 31U };
	const u32 lane_fields = BIT(30) | GENMASK(12, 10);
	u32 allocated_neighbours = 0;
	u32 fixed_neighbours = 0;
	u32 unallocated_neighbours = 0;
	size_t index;

	KUNIT_ASSERT_NOT_NULL(test, artifact);
	for (index = 0; index < ARRAY_SIZE(orlix_tcti_advsimd_structure_contracts);
	     index++) {
		const struct orlix_tcti_advsimd_structure_contract *contract =
			&orlix_tcti_advsimd_structure_contracts[index];
		u32 free_lane_fields = lane_fields & ~contract->mask;
		bool free_rm = !(contract->mask & GENMASK(20, 16));
		u8 rd_index;
		u8 rn_index;
		u8 rm_index;
		u8 lane_variant;
		u8 bit;

		KUNIT_EXPECT_EQ_MSG(test,
			ORLIX_TCTI_ADVSIMD_STRUCTURE_ADDRESSING_NOT_APPLICABLE_NO_ENCODING,
			orlix_tcti_advsimd_structure_addressing_applicability(contract,
				ORLIX_TCTI_MEMORY_INDEX_PRE),
			"ordinal=%u leaf=%s pre-index", contract->ordinal,
			contract->leaf_id);

		/*
		 * Exercise every lane/size bit left free by the authoritative mask,
		 * plus SP, register boundaries, list wrap, base/list overlap, and
		 * register/immediate writeback boundaries.
		 */
		for (lane_variant = 0; lane_variant < 16; lane_variant++) {
			u32 lane_encoding =
				((lane_variant & 8U) ? BIT(30) : 0U) |
				FIELD_PREP(GENMASK(12, 10), lane_variant & 7U);

			for (rd_index = 0; rd_index < ARRAY_SIZE(boundaries); rd_index++)
				for (rn_index = 0; rn_index < ARRAY_SIZE(boundaries);
				     rn_index++)
					for (rm_index = 0;
					     rm_index < (free_rm ? ARRAY_SIZE(boundaries) : 1U);
					     rm_index++) {
						struct orlix_tcti_decoded_instruction decoded;
						u32 instruction = contract->pattern;
						u8 expected_access_size;
						u8 expected_lane_index;

						instruction = (instruction & ~free_lane_fields) |
							(lane_encoding & free_lane_fields);
						instruction = (instruction & ~GENMASK(4, 0)) |
							FIELD_PREP(GENMASK(4, 0), boundaries[rd_index]);
						instruction = (instruction & ~GENMASK(9, 5)) |
							FIELD_PREP(GENMASK(9, 5), boundaries[rn_index]);
						if (free_rm)
							instruction = (instruction & ~GENMASK(20, 16)) |
								FIELD_PREP(GENMASK(20, 16),
									boundaries[rm_index]);
						KUNIT_ASSERT_EQ_MSG(test, contract->pattern,
							instruction & contract->mask,
							"ordinal=%u leaf=%s instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						decoded = orlix_tcti_decode_aarch64(instruction);
						expected_access_size =
							orlix_tcti_advsimd_structure_access_size(contract,
								instruction);
						expected_lane_index =
							orlix_tcti_advsimd_structure_lane_index(contract,
								instruction);
						KUNIT_EXPECT_EQ_MSG(test, contract->decode_class,
							decoded.decode_class,
							"ordinal=%u leaf=%s instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test, contract->load, decoded.load,
							"ordinal=%u leaf=%s instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test, contract->structure_count,
							decoded.simd_structure_count,
							"ordinal=%u leaf=%s instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test, contract->index_mode,
							decoded.memory_index_mode,
							"ordinal=%u leaf=%s instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test,
							FIELD_GET(GENMASK(4, 0), instruction), decoded.rd,
							"ordinal=%u leaf=%s rd instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test,
							FIELD_GET(GENMASK(9, 5), instruction), decoded.rn,
							"ordinal=%u leaf=%s rn instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test,
							FIELD_GET(GENMASK(20, 16), instruction), decoded.rm,
							"ordinal=%u leaf=%s rm instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test, expected_access_size,
							decoded.access_size,
							"ordinal=%u leaf=%s access-size instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test, expected_lane_index,
							decoded.simd_lane_index,
							"ordinal=%u leaf=%s lane instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
						KUNIT_EXPECT_EQ_MSG(test, !!(instruction & BIT(30)),
							decoded.simd_q,
							"ordinal=%u leaf=%s q instruction=%#x",
							contract->ordinal, contract->leaf_id, instruction);
					}
		}

		/* Classify each fixed-bit neighbour against all 4,350 direct leaves. */
		for (bit = 0; bit < 32; bit++) {
			u32 complement;
			u32 class_pattern;
			struct orlix_tcti_decoded_instruction decoded;
			bool complete_match;
			bool family_match;
			bool inventory_overlap;

			if (!(contract->mask & BIT(bit)))
				continue;
			complement = contract->pattern ^ BIT(bit);
			class_pattern = complement & contract->mask;
			complete_match =
				orlix_tcti_advsimd_structure_complete_inventory_matches(artifact,
					complement);
			family_match =
				orlix_tcti_advsimd_structure_matches_authoritative_leaf(complement);
			inventory_overlap =
				orlix_tcti_advsimd_structure_class_overlaps_complete_inventory(
					artifact, contract->mask, class_pattern);
			fixed_neighbours++;
			if (inventory_overlap)
				allocated_neighbours++;
			else
				unallocated_neighbours++;
			if (family_match)
				KUNIT_EXPECT_TRUE_MSG(test, complete_match,
					"ordinal=%u leaf=%s complement-bit=%u instruction=%#x",
					contract->ordinal, contract->leaf_id, bit, complement);
			decoded = orlix_tcti_decode_aarch64(complement);
			if (!family_match)
				KUNIT_EXPECT_FALSE_MSG(test,
					orlix_tcti_advsimd_structure_is_family_decode(
						decoded.decode_class),
					"ordinal=%u leaf=%s complement-bit=%u instruction=%#x",
					contract->ordinal, contract->leaf_id, bit, complement);
			if (!inventory_overlap) {
				KUNIT_EXPECT_FALSE_MSG(test, complete_match,
					"ordinal=%u leaf=%s complement-bit=%u instruction=%#x",
					contract->ordinal, contract->leaf_id, bit, complement);
				KUNIT_EXPECT_EQ_MSG(test, ORLIX_TCTI_DECODE_UNSUPPORTED,
					decoded.decode_class,
					"ordinal=%u leaf=%s complement-bit=%u instruction=%#x",
					contract->ordinal, contract->leaf_id, bit, complement);
			}
		}
	}
	KUNIT_EXPECT_GT(test, fixed_neighbours, 0U);
	KUNIT_EXPECT_GT(test, allocated_neighbours, 0U);
	KUNIT_EXPECT_GT(test, unallocated_neighbours, 0U);
	KUNIT_EXPECT_EQ(test, fixed_neighbours,
		allocated_neighbours + unallocated_neighbours);
}


