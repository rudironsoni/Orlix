#define ORLIX_TCTI_ADVSIMD_STRUCTURE_FIRST_SOURCE 2353U
#define ORLIX_TCTI_ADVSIMD_STRUCTURE_LAST_SOURCE  2504U
#define ORLIX_TCTI_ADVSIMD_STRUCTURE_SOURCE_COUNT \
	(ORLIX_TCTI_ADVSIMD_STRUCTURE_LAST_SOURCE - \
	 ORLIX_TCTI_ADVSIMD_STRUCTURE_FIRST_SOURCE + 1U)
#define ORLIX_TCTI_ADVSIMD_STRUCTURE_SVC 0xd4000001U

struct orlix_tcti_advsimd_structure_context {
	u64 simd[ARRAY_SIZE(current->thread.user_simd)];
	unsigned long simd_valid;
	unsigned long fpcr;
	unsigned long fpsr;
};

static int orlix_tcti_advsimd_structure_test_init(struct kunit *test)
{
	struct orlix_tcti_advsimd_structure_context *context;

	context = kunit_kzalloc(test, sizeof(*context), GFP_KERNEL);
	if (!context)
		return -ENOMEM;
	memcpy(context->simd, current->thread.user_simd, sizeof(context->simd));
	context->simd_valid = current->thread.user_simd_valid;
	context->fpcr = current->thread.user_fpcr;
	context->fpsr = current->thread.user_fpsr;
	test->priv = context;
	return 0;
}

static void orlix_tcti_advsimd_structure_test_exit(struct kunit *test)
{
	struct orlix_tcti_advsimd_structure_context *context = test->priv;

	memcpy(current->thread.user_simd, context->simd, sizeof(context->simd));
	current->thread.user_simd_valid = context->simd_valid;
	current->thread.user_fpcr = context->fpcr;
	current->thread.user_fpsr = context->fpsr;
}

static const char *orlix_tcti_advsimd_structure_artifact_string(
	const struct orlix_tcti_target_instruction_artifact *artifact, u32 offset)
{
	if (offset >= artifact->string_pool_size)
		return NULL;
	return (const char *)artifact->string_pool + offset;
}

/*
 * This is an independent pinned contract for every direct AARCHMRS leaf in
 * the classic AdvSIMD structure interval.  It intentionally does not include
 * the source manifest: manifest drift and decoder drift must fail separately.
 */
enum orlix_tcti_advsimd_structure_lane_shape {
	ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE_NONE,
	ORLIX_TCTI_ADVSIMD_STRUCTURE_LANE,
	ORLIX_TCTI_ADVSIMD_STRUCTURE_REPLICATE,
};

struct orlix_tcti_advsimd_structure_contract {
	u32 ordinal;
	const char *leaf_id;
	const char *mnemonic;
	const char *operation_id;
	u32 mask;
	u32 pattern;
	enum orlix_tcti_decode_class decode_class;
	bool load;
	u8 structure_count;
	u8 access_size;
	u8 q0_semantic_width;
	u8 q1_semantic_width;
	enum orlix_tcti_memory_index_mode index_mode;
	enum orlix_tcti_advsimd_structure_lane_shape lane_shape;
	bool interleaved;
};

