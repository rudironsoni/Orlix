static void orlix_tcti_advsimd_structure_fault_preserves_pc_and_writeback(
	struct kunit *test)
{
	struct pt_regs regs = {};
	struct pt_regs before_regs;
	struct orlix_tcti_decoded_instruction decoded;
	struct orlix_tcti_result result;
	unsigned long address;
	unsigned long mapped;
	u64 before_simd[ARRAY_SIZE(current->thread.user_simd)];
	unsigned long before_valid;
	unsigned long before_fpcr;
	unsigned long before_fpsr;

	KUNIT_ASSERT_NOT_NULL(test, current->mm);
	address = ksys_mmap_pgoff(0, 2 * PAGE_SIZE, PROT_READ | PROT_WRITE,
				 MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
	KUNIT_ASSERT_FALSE(test, IS_ERR_VALUE(address));
	KUNIT_ASSERT_EQ(test, 0,
		sys_mprotect(address + PAGE_SIZE, PAGE_SIZE, PROT_NONE));

	/* LD2 {v3.8h, v4.8h}, [x10].  The first transfer faults. */
	decoded = orlix_tcti_decode_aarch64(0x0c408543U);
	KUNIT_ASSERT_EQ(test, ORLIX_TCTI_DECODE_SIMD_LOAD_STORE_MULTIPLE_STRUCTURE,
			decoded.decode_class);
	orlix_tcti_advsimd_structure_initialize_state(&regs, 0x0c408543U);
	regs.regs[10] = address + PAGE_SIZE;
	before_regs = regs;
	memcpy(before_simd, current->thread.user_simd, sizeof(before_simd));
	before_valid = current->thread.user_simd_valid;
	before_fpcr = current->thread.user_fpcr;
	before_fpsr = current->thread.user_fpsr;

	mapped = orlix_tcti_advsimd_structure_map_instruction(test, 0x0c408543U);
	regs.pc = mapped;
	before_regs.pc = mapped;
	regs.pstate |= PSR_MODE_EL0t;
	regs.syscallno = NO_SYSCALL;
	result = orlix_tcti_resume_user(current, &regs, current->mm);
	KUNIT_EXPECT_EQ(test, ORLIX_TCTI_EXIT_USER_FAULT, result.reason);
	KUNIT_EXPECT_EQ(test, -EFAULT, result.status);
	KUNIT_EXPECT_EQ(test, address + PAGE_SIZE, result.fault_address);
	KUNIT_EXPECT_EQ(test, ORLIX_TCTI_ACCESS_READ, result.fault_access);
	KUNIT_EXPECT_EQ(test, mapped, result.pc);
	KUNIT_EXPECT_MEMEQ(test, &before_regs, &regs, sizeof(regs));
	KUNIT_EXPECT_MEMEQ(test, before_simd, current->thread.user_simd,
			   sizeof(before_simd));
	KUNIT_EXPECT_EQ(test, before_valid, current->thread.user_simd_valid);
	KUNIT_EXPECT_EQ(test, before_fpcr, current->thread.user_fpcr);
	KUNIT_EXPECT_EQ(test, before_fpsr, current->thread.user_fpsr);

	KUNIT_EXPECT_EQ(test, 0, vm_munmap(mapped, PAGE_SIZE));
	KUNIT_EXPECT_EQ(test, 0, vm_munmap(address, 2 * PAGE_SIZE));
}

